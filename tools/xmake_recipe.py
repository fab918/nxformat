"""Writes packages/n/nxformat/xmake.lua from packages/n/nxformat/versions.json.

    python tools/xmake_recipe.py                       # regenerate
    python tools/xmake_recipe.py --add 1.0.0 SHA256SUMS  # record a release

The release workflow runs the second form with the SHA256SUMS of the
archives it publishes, then attaches the populated repository to the release.
It does not commit generated hashes back to main.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDER = ROOT / 'packages/n/nxformat'
VERSIONS = FOLDER / 'versions.json'
REPOSITORY = 'https://github.com/fab918/nxformat'

TEMPLATE = '''-- Generated by tools/xmake_recipe.py from versions.json; do not edit.
--
-- In a project:
--     add_repositories("nxformat /path/to/extracted/nxformat-xmake")
--     add_requires("nxformat")              -- or {{configs = {{shared = false}}}}
--     target("app")
--         add_packages("nxformat")
package("nxformat")
    set_homepage("{repository}")
    set_license("MIT")
    set_description("NX game archives: the nxconvert C API (nxformat.h) and the header-only C++17 reader")

    add_configs("shared", {{description = "Use the shared library (else the static one).", default = true, type = "boolean"}})

    on_source(function (package)
        -- version -> platform -> sha256 of nxformat-<version>-<platform> archive
        local builds = {{
{builds}
        }}
        local name
        if package:is_plat("windows") and package:is_arch("x64", "x86_64") then
            name = "windows-x64"
        elseif package:is_plat("linux") and package:is_arch("x86_64") then
            name = "linux-x64"
        elseif package:is_plat("linux") and package:is_arch("arm64", "arm64-v8a", "aarch64") then
            name = "linux-arm64"
        elseif package:is_plat("macosx") then
            name = "macos-universal"
        elseif package:is_plat("android") and package:is_arch("arm64-v8a", "arm64") then
            name = "android-arm64"
        end
        if not name then
            return
        end
        local ext = package:is_plat("windows") and ".zip" or ".tar.gz"
        package:set("urls", "{repository}/releases/download/V$(version)/nxformat-$(version)-" .. name .. ext)
        for version, hashes in pairs(builds) do
            if hashes[name] then
                package:add("versions", version, hashes[name])
            end
        end
    end)

    on_load(function (package)
        if package:config("shared") then
            package:add("links", "nxformat")
            if package:is_plat("windows") then
                package:addenv("PATH", "bin")
            end
        else
            package:add("links", "nxformat_static")
            package:add("defines", "NXFORMAT_STATIC")
            if package:is_plat("windows") then
                package:add("syslinks", "ws2_32", "userenv", "ntdll", "bcrypt", "advapi32", "kernel32", "synchronization")
            elseif package:is_plat("linux") then
                package:add("syslinks", "pthread", "dl", "m")
            elseif package:is_plat("android") then
                package:add("syslinks", "dl", "m", "log")
            end
        end
    end)

    on_install("windows|x64", "linux|x86_64", "linux|arm64", "macosx", "android|arm64-v8a", function (package)
        os.cp("include/*", package:installdir("include"))
        os.cp("lib/*", package:installdir("lib"))
        if os.isfile("LICENSE") then
            os.cp("LICENSE", package:installdir())
        end
        if os.isdir("bin") then
            os.cp("bin/*", package:installdir("bin"))
        end
    end)

    on_test(function (package)
        assert(package:has_cfuncs("nxformat_version", {{includes = "nxformat.h"}}))
    end)
'''


def write(versions: dict) -> None:
    lines = []
    for version in sorted(versions, key=lambda v: [int(x) for x in re.findall(r'\d+', v)], reverse=True):
        lines.append(f'            ["{version}"] = {{')
        for platform, digest in sorted(versions[version].items()):
            lines.append(f'                ["{platform}"] = "{digest}",')
        lines.append('            },')
    FOLDER.mkdir(parents=True, exist_ok=True)
    VERSIONS.write_text(json.dumps(versions, indent=2, sort_keys=True) + '\n', newline='\n')
    (FOLDER / 'xmake.lua').write_text(
        TEMPLATE.format(repository=REPOSITORY, builds='\n'.join(lines)), newline='\n')


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument('--add', nargs=2, metavar=('VERSION', 'SHA256SUMS'))
    a = p.parse_args()
    versions = json.loads(VERSIONS.read_text()) if VERSIONS.exists() else {}
    if a.add:
        version, sums = a.add
        hashes = {}
        pattern = re.compile(rf'^([0-9a-f]{{64}})\s+\*?nxformat-{re.escape(version)}-(.+?)\.(?:zip|tar\.gz)$')
        for line in Path(sums).read_text().splitlines():
            m = pattern.match(line.strip())
            if m:
                hashes[m.group(2)] = m.group(1)
        if not hashes:
            print(f'no nxformat-{version} archives in {sums}', file=sys.stderr)
            return 1
        versions[version] = hashes
    write(versions)
    return 0


if __name__ == '__main__':
    sys.exit(main())
